<h1>Existing Documents (ZIP Upload)</h1>

<p>
  If you already have individually prepared PDFs or DOCX files — for example, certificates generated by another system —
  you can upload them as a ZIP archive. MergeMail will match each file to the correct recipient and attach it to their email.
</p>

<h2>When to Use This Mode</h2>

<ul>
  <li>You have a batch of pre-generated, individually named PDF certificates.</li>
  <li>You received signed contract PDFs that need to be sent to each signatory.</li>
  <li>Another system generated the documents and you only need the email delivery part.</li>
</ul>

<p>
  If you want MergeMail to <em>generate</em> documents from a template, use the
  <a href="/docs/document-templates" class="text-brand-600 no-underline hover:underline">DOCX/PDF template mode</a> instead.
</p>

<h2>Preparing Your ZIP Archive</h2>

<ol>
  <li>Name each file in a way that can be matched to a row in your spreadsheet — typically using a unique identifier like email address, student ID, or name.</li>
  <li>Place all files in the root of the ZIP (not in subdirectories) for best results.</li>
  <li>The archive may contain PDFs, DOCX files, or a mix.</li>
  <li>Maximum ZIP file size: <strong>200 MB</strong>.</li>
  <li>Maximum files in archive: <strong>5,000</strong>.</li>
</ol>

<h3>Recommended File Naming</h3>

<ul>
  <li><code>adaeze_okonkwo.pdf</code> — matched against the <code>full_name</code> column.</li>
  <li><code>CERT-0001.pdf</code> — matched against a <code>certificate_id</code> column.</li>
  <li><code>adaeze@example.com.pdf</code> — matched against the email column (highest confidence).</li>
</ul>

<h2>Matching Logic</h2>

<p>MergeMail uses a scoring algorithm to match filenames to rows:</p>

<ol>
  <li><strong>Exact email match</strong> — If the filename (without extension) is an email address that appears in the email column, it is an exact match (confidence: high).</li>
  <li><strong>Exact ID match</strong> — If the filename matches a value in any column exactly, it is a high-confidence match.</li>
  <li><strong>Normalized name match</strong> — The filename is normalized (spaces→underscores, lowercase) and compared against normalized column values. Partial matches score lower.</li>
  <li><strong>No match</strong> — Files that cannot be matched are listed as unmatched. You can manually assign them.</li>
</ol>

<h2>The Matching Preview</h2>

<p>
  After uploading the ZIP, the <strong>Matching Preview</strong> screen shows every file alongside its matched recipient row and confidence level.
  You can:
</p>

<ul>
  <li>Accept auto-matches and proceed.</li>
  <li>Manually reassign a file to a different row.</li>
  <li>Mark files as "no attachment" for rows where no matching file exists.</li>
  <li>Remove files that do not belong to any recipient.</li>
</ul>

<h2>Security Constraints</h2>

<p>For security, MergeMail enforces the following on ZIP uploads:</p>

<ul>
  <li>File paths that use <code>../</code> path traversal are rejected.</li>
  <li>Executable files (<code>.exe</code>, <code>.sh</code>, <code>.js</code>, etc.) inside the ZIP are rejected.</li>
  <li>ZIP bombs (highly compressed archives that expand to large sizes) are detected and rejected. The decompressed size limit is 500 MB.</li>
  <li>Only <code>.pdf</code> and <code>.docx</code> files are processed; all other file types in the archive are ignored.</li>
</ul>

<h2>Manual Override</h2>

<p>
  If automatic matching fails for a row, the recipient still receives an email — just without a document attachment.
  Use the matching preview to manually assign the correct file before launching the campaign.
</p>

