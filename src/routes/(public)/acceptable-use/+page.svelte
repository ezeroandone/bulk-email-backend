  <h1 class="text-4xl font-extrabold text-neutral-900 mb-2">Acceptable Use Policy</h1>
  <p class="text-sm text-neutral-500 mb-10">Last updated: December 2024</p>

  <div class="prose prose-neutral max-w-none">

    <p>
      This Acceptable Use Policy ("AUP") governs your use of the MergeMail platform.
      It is incorporated into the <a href="/terms" class="text-brand-600 no-underline hover:underline">Terms of Service</a> by reference.
      Violations of this AUP may result in immediate account suspension without refund.
    </p>

    <h2>1. Permitted Use</h2>
    <p>MergeMail is designed for legitimate, permission-based bulk communications, including:</p>
    <ul>
      <li>Sending personalized transactional emails to opt-in recipients (e.g. certificates to graduates, invoices to clients, confirmations to registrants).</li>
      <li>Distributing newsletters, updates, or announcements to subscribers who have explicitly opted in.</li>
      <li>Sending membership renewal reminders, event invitations, and status updates to existing members or customers.</li>
      <li>HR and admissions communications to individuals who have applied to your organization.</li>
      <li>Any other legitimate email communication where the recipient has a reasonable expectation of receiving your message.</li>
    </ul>

    <h2>2. Prohibited Use</h2>
    <p>You may <strong>not</strong> use MergeMail for any of the following:</p>

    <h3>Spam and Unsolicited Email</h3>
    <ul>
      <li>Sending unsolicited bulk email (spam) to any recipients who have not opted in to receive your communications.</li>
      <li>Harvesting or purchasing email address lists for cold outreach.</li>
      <li>Sending more than one unsolicited message to any recipient after they have asked not to receive further emails from you.</li>
    </ul>

    <h3>Phishing and Fraud</h3>
    <ul>
      <li>Creating or sending phishing emails that impersonate banks, government agencies, other companies, or individuals to steal credentials or personal information.</li>
      <li>Sending fraudulent messages designed to deceive recipients into transferring money or providing financial information.</li>
      <li>Using spoofed sender addresses or misleading subject lines to disguise the origin or nature of an email.</li>
    </ul>

    <h3>Harassment and Abuse</h3>
    <ul>
      <li>Sending threatening, harassing, or abusive messages to any recipient.</li>
      <li>Using MergeMail to target individuals based on race, ethnicity, religion, gender, sexual orientation, disability, or other protected characteristics.</li>
      <li>Any coordinated campaign designed to harass, intimidate, or silence a specific individual or group.</li>
    </ul>

    <h3>Illegal Content</h3>
    <ul>
      <li>Distributing malware, ransomware, spyware, or any malicious software via email attachments or links.</li>
      <li>Sending content that is illegal under Nigerian law or the law of the recipient's jurisdiction, including content that promotes illegal drugs, human trafficking, child exploitation, or terrorism.</li>
      <li>Violating intellectual property rights of third parties in email content or attachments.</li>
    </ul>

    <h3>Platform Abuse</h3>
    <ul>
      <li>Attempting to circumvent credit deduction mechanisms or abuse free credit grants.</li>
      <li>Sharing account credentials to allow multiple users to access a single account.</li>
      <li>Using automated scripts or bots to interact with MergeMail's UI or APIs in ways not intended for normal use.</li>
      <li>Attempting to reverse-engineer, decompile, or extract the source code of the platform.</li>
    </ul>

    <h2>3. Enforcement</h2>
    <p>
      We monitor for AUP violations through automated signals (high bounce rates, spam complaints) and user reports.
      Upon detecting a violation we may take any of the following actions, at our sole discretion:
    </p>
    <ul>
      <li>Issue a warning and request that the violating content be removed.</li>
      <li>Pause the offending campaign immediately.</li>
      <li>Suspend the account pending investigation.</li>
      <li>Permanently terminate the account and forfeit remaining credits.</li>
      <li>Report the activity to relevant authorities in Nigeria or other applicable jurisdictions.</li>
    </ul>
    <p>
      Accounts terminated for AUP violations are not entitled to refunds of any kind, including refunds of unused credits.
    </p>

    <h2>4. Reporting Violations</h2>
    <p>
      If you believe someone is using MergeMail to send spam, conduct phishing attacks, or violate this AUP,
      please report it using the <a href="/contact" class="text-brand-600 no-underline hover:underline">contact form</a>
      with subject "Report Abuse". Include as much detail as possible:
    </p>
    <ul>
      <li>The sender's email address or domain.</li>
      <li>The full email headers (if available).</li>
      <li>A description of the violation and any evidence.</li>
    </ul>
    <p>We treat all abuse reports seriously and respond within 1 business day.</p>

    <h2>5. Updates to This Policy</h2>
    <p>
      We may update this AUP to address new threats or changes in applicable law.
      Updates will be announced in the dashboard. Continued use of MergeMail after an update constitutes acceptance of the revised AUP.
    </p>

