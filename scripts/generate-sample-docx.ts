/**
 * Generates static/examples/sample-template.docx
 *
 * Creates a Certificate of Participation template with docxtemplater-compatible
 * {{variable}} placeholders.
 *
 * Run: npx tsx scripts/generate-sample-docx.ts
 */
import PizZip from 'pizzip';
import Docxtemplater from 'docxtemplater';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = path.resolve(__dirname, '../static/examples');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'sample-template.docx');

// ── Minimal DOCX XML template ─────────────────────────────────────────────────
// We build the DOCX from scratch using PizZip + raw Open XML.
// This produces a valid .docx that docxtemplater can render.

function buildDocxXml(): string {
  // docxtemplater uses single-brace delimiters by default: {variable}
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document
  xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"
  xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
  xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"
  mc:Ignorable="">
  <w:body>

    <!-- Certificate Title -->
    <w:p>
      <w:pPr>
        <w:jc w:val="center"/>
      </w:pPr>
      <w:r>
        <w:rPr>
          <w:b/>
          <w:sz w:val="52"/>
          <w:szCs w:val="52"/>
        </w:rPr>
        <w:t>CERTIFICATE OF PARTICIPATION</w:t>
      </w:r>
    </w:p>

    <!-- Spacer -->
    <w:p><w:pPr><w:jc w:val="center"/></w:pPr></w:p>

    <!-- "This is to certify that" -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="28"/></w:rPr>
        <w:t>This is to certify that</w:t>
      </w:r>
    </w:p>

    <!-- Full name placeholder: {full_name} -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr>
          <w:b/>
          <w:sz w:val="40"/>
        </w:rPr>
        <w:t>{full_name}</w:t>
      </w:r>
    </w:p>

    <!-- Body text -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="28"/></w:rPr>
        <w:t xml:space="preserve">has successfully participated in this event and is hereby awarded this certificate.</w:t>
      </w:r>
    </w:p>

    <!-- Spacer -->
    <w:p><w:pPr><w:jc w:val="center"/></w:pPr></w:p>

    <!-- Membership No: {mem_no} -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="24"/></w:rPr>
        <w:t xml:space="preserve">Membership No: </w:t>
      </w:r>
      <w:r>
        <w:rPr><w:b/><w:sz w:val="24"/></w:rPr>
        <w:t>{mem_no}</w:t>
      </w:r>
    </w:p>

    <!-- Certificate ID: {certificate_id} -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="24"/></w:rPr>
        <w:t xml:space="preserve">Certificate ID: </w:t>
      </w:r>
      <w:r>
        <w:rPr><w:b/><w:sz w:val="24"/></w:rPr>
        <w:t>{certificate_id}</w:t>
      </w:r>
    </w:p>

    <!-- Date: {date} -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="24"/></w:rPr>
        <w:t xml:space="preserve">Date: </w:t>
      </w:r>
      <w:r>
        <w:rPr><w:b/><w:sz w:val="24"/></w:rPr>
        <w:t>{date}</w:t>
      </w:r>
    </w:p>

    <!-- Spacer -->
    <w:p><w:pPr><w:jc w:val="center"/></w:pPr></w:p>

    <!-- Footer note -->
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r>
        <w:rPr><w:sz w:val="20"/><w:color w:val="888888"/></w:rPr>
        <w:t>Generated by MergeMail</w:t>
      </w:r>
    </w:p>

    <!-- Section properties -->
    <w:sectPr>
      <w:pgSz w:w="12240" w:h="15840"/>
      <w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/>
    </w:sectPr>

  </w:body>
</w:document>`;
}

function buildRelationships(): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1"
    Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles"
    Target="styles.xml"/>
  <Relationship Id="rId2"
    Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/settings"
    Target="settings.xml"/>
</Relationships>`;
}

function buildStyles(): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:style w:type="paragraph" w:styleId="Normal">
    <w:name w:val="Normal"/>
    <w:rPr>
      <w:sz w:val="24"/>
      <w:szCs w:val="24"/>
    </w:rPr>
  </w:style>
  <w:style w:type="paragraph" w:styleId="Heading1">
    <w:name w:val="heading 1"/>
    <w:basedOn w:val="Normal"/>
    <w:rPr>
      <w:b/>
      <w:sz w:val="52"/>
      <w:szCs w:val="52"/>
    </w:rPr>
  </w:style>
</w:styles>`;
}

function buildSettings(): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:settings xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:defaultTabStop w:val="720"/>
</w:settings>`;
}

function buildContentTypes(): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml"
    ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
  <Override PartName="/word/styles.xml"
    ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>
  <Override PartName="/word/settings.xml"
    ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.settings+xml"/>
</Types>`;
}

function buildPackageRels(): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1"
    Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument"
    Target="word/document.xml"/>
</Relationships>`;
}

async function main(): Promise<void> {
  // Ensure output directory exists
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  // Build the DOCX ZIP manually
  const zip = new PizZip();

  zip.file('[Content_Types].xml', buildContentTypes());
  zip.file('_rels/.rels', buildPackageRels());
  zip.file('word/document.xml', buildDocxXml());
  zip.file('word/_rels/document.xml.rels', buildRelationships());
  zip.file('word/styles.xml', buildStyles());
  zip.file('word/settings.xml', buildSettings());

  // Verify docxtemplater can parse and render the template
  const testZip = new PizZip(zip.generate({ type: 'nodebuffer' }));
  const doc = new Docxtemplater(testZip, { paragraphLoop: true, linebreaks: true });
  doc.render({
    full_name: 'Test User',
    mem_no: 'N001',
    certificate_id: 'CERT-001',
    date: new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  });
  console.log('  Verification render: OK');

  // The original zip (unrendered) is the template output
  const buffer = zip.generate({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 }
  });

  fs.writeFileSync(OUTPUT_FILE, buffer);
  console.log(`✓ Written: ${OUTPUT_FILE}`);
  console.log('  Placeholders: {full_name}, {mem_no}, {certificate_id}, {date}');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
